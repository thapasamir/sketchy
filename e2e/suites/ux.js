const puppeteer = require('puppeteer-core')
const wait = ms => new Promise(r => setTimeout(r, ms))
const { U, launch } = require('../lib/browser')
const click = (p, t) => p.evaluate(t => { const b=[...document.querySelectorAll('button')].find(x => x.textContent.trim()===t); if(!b) throw new Error('no button "'+t+'"'); b.click() }, t)
const has = (p, t) => p.evaluate(t => document.body.innerText.includes(t), t)
const { playerRows: players } = require('../lib/lobby')
const path = p => p.evaluate(() => location.pathname)
const exists = (p, sel) => p.$(sel).then(Boolean)
let fails = 0
const ok = (n, c, x='') => { if(!c) fails++; console.log(c ? 'PASS' : 'FAIL', n, x) }
async function open(b, w=1100, h=800, url=U+'/') {
  const ctx = await b.createBrowserContext(); const p = await ctx.newPage(); await p.setViewport({ width: w, height: h })
  p.errs = []; p.on('pageerror', e => p.errs.push(e.message))
  await p.evaluateOnNewDocument(() => localStorage.setItem('sketchy:seen-how-to-play', 'true'))
  await p.goto(url, { waitUntil: 'networkidle0' }); return p
}
;(async () => {
  const b = await launch()
  const shots = process.argv[2]

  console.log('--- new visitor / guest ---')
  const g = await open(b)
  ok('new visitor sees landing with both options', await has(g,'Play as Guest') && await has(g,'Log in / Sign up'))
  await click(g, 'Play as Guest'); await g.waitForSelector('#name')
  ok('guest is asked for a name, field is focused', await g.evaluate(() => document.activeElement.id) === 'name')
  await g.screenshot({ path: shots + '/ux-guest-dashboard.png' })
  await g.type('#name', 'Alice'); await g.keyboard.press('Enter'); await g.waitForSelector('#room-code')
  const code = await g.$eval('#room-code', e => e.textContent.trim())
  ok('Enter key creates the room', /^[A-Z]{4}$/.test(code), code)
  ok('URL is the shareable room link', await path(g) === '/room/' + code)
  ok('tab title shows the room', (await g.title()).includes(code))

  await g.reload({ waitUntil: 'networkidle0' }); await g.waitForSelector('#room-code')
  ok('refresh in lobby keeps you in the same room', await g.$eval('#room-code', e => e.textContent.trim()) === code && (await players(g))[0].startsWith('Alice'))

  await click(g, '← Leave'); await g.waitForSelector('#name')
  ok('Leave returns to dashboard at "/"', await path(g) === '/')
  ok('guest name is remembered', await g.$eval('#name', e => e.value) === 'Alice')
  await g.reload({ waitUntil: 'networkidle0' })
  ok('reload at "/" shows the landing page, offering to continue', await exists(g, '#home-continue') && !(await has(g,'Play as Guest')))
  await click(g, 'Continue as Alice'); await g.waitForSelector('#name')

  console.log('--- invite link (second person) ---')
  await click(g, 'Create Room'); await g.waitForSelector('#room-code')
  const code2 = await g.$eval('#room-code', e => e.textContent.trim())
  const f = await open(b, 390, 844, `${U}/room/${code2}`)
  ok('invite link shows the invitation on landing', await has(f, `invited to room ${code2}`))
  await f.screenshot({ path: shots + '/ux-invite-landing-phone.png' })
  await click(f, 'Play as Guest'); await f.waitForSelector('#name')
  ok('code is prefilled from the link', await f.$eval('#code', e => e.value) === code2)
  await f.screenshot({ path: shots + '/ux-invite-dashboard-phone.png' })
  await f.type('#name', 'Priya'); await f.keyboard.press('Enter'); await f.waitForSelector('#room-code')
  await wait(500)
  const hl = await players(g)
  ok('invitee joined, host saw it live', hl.length === 2 && hl[1].startsWith('Priya'), JSON.stringify(hl))
  ok('invitee refresh keeps seat on phone', (await (async()=>{ await f.reload({waitUntil:'networkidle0'}); await f.waitForSelector('#room-code'); return players(f) })()).length === 2)

  console.log('--- registered user ---')
  const r = await open(b)
  await click(r, 'Log in / Sign up'); await r.waitForSelector('#login-username')
  ok('login screen focuses the username', await r.evaluate(() => document.activeElement.id) === 'login-username')
  await click(r, 'New here? Create an account'); await r.waitForSelector('#reg-username')
  const uname = 'user' + Date.now().toString().slice(-6)
  await r.type('#reg-username', uname); await r.type('#reg-email', uname + '@example.com'); await r.type('#reg-password', 'secret123')
  await r.keyboard.press('Enter'); await r.waitForSelector('#code')
  ok('register by Enter logs you in', await has(r, 'Hi,') && await has(r, uname))
  ok('registered user is NOT asked for a name', !(await exists(r, '#name')))
  ok('no "Play as Guest" for a signed-in user', !(await has(r, 'Play as Guest')))
  await r.screenshot({ path: shots + '/ux-registered-dashboard.png' })
  await click(r, 'Create Room'); await r.waitForSelector('#room-code')
  ok('one click creates a room under the username', (await players(r))[0].startsWith(uname))
  await click(r, '← Leave'); await r.waitForSelector('#code')
  await r.reload({ waitUntil: 'networkidle0' })
  ok('login survives reload: the landing page offers to continue', await exists(r, '#home-continue') && !(await has(r, 'Play as Guest')))
  await click(r, `Continue as ${uname}`); await r.waitForSelector('#code')
  ok('...and continuing opens the dashboard', await has(r, 'Hi,') && !(await exists(r, '#name')))
  await click(r, 'Log out'); await wait(200)
  ok('log out returns to landing', await has(r, 'Play as Guest'))
  await click(r, 'Log in / Sign up'); await r.waitForSelector('#login-username')
  await r.type('#login-username', uname); await r.type('#login-password', 'nope'); await r.keyboard.press('Enter'); await wait(700)
  ok('wrong password shows a readable error', await has(r, 'incorrect'))
  await r.$eval('#login-password', e => e.value = ''); await r.type('#login-password', 'secret123'); await r.keyboard.press('Enter'); await r.waitForSelector('#code')
  ok('log in by Enter works', await has(r, 'Hi,'))

  console.log('--- edge cases ---')
  await r.evaluate(() => localStorage.setItem('sketchy:seat', JSON.stringify({ code: 'ZZZZ', playerId: 'ghost' })))
  await r.goto(U + '/', { waitUntil: 'networkidle0' }); await r.waitForSelector('#home-rejoin'); await r.click('#home-rejoin'); await r.waitForSelector('#code'); await wait(600)
  ok('closed room: sent to dashboard with explanation', await has(r, 'has closed') && await exists(r, '#code'))
  ok('stale seat was cleared', await r.evaluate(() => localStorage.getItem('sketchy:seat')) === null)
  const bad = await open(b, 1100, 800, U + '/room/QQQQ')
  await click(bad, 'Play as Guest'); await bad.waitForSelector('#name'); await bad.type('#name', 'Zed'); await bad.keyboard.press('Enter'); await wait(700)
  ok('invite to a non-existent room shows a clear error', await has(bad, 'No room with that code'))
  await click(g, '← Leave'); await g.waitForSelector('#code')
  await click(g, 'Create Room'); await g.waitForSelector('#room-code'); await g.goBack(); await wait(400)
  ok('browser Back from a room leaves it', await path(g) === '/' && await exists(g, '#code'))

  const errs = [g,f,r,bad].flatMap(p => p.errs)
  ok('no page errors', errs.length === 0, errs.join('|'))
  console.log(fails ? `\n${fails} FAILED` : '\nALL PASSED')
  await b.close()
})().catch(e => { console.log('CRASH', e.message); process.exit(1) })
